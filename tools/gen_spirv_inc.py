#!/usr/bin/env python3
"""Compile GLSL shaders to SPIR-V C arrays: gen_spirv_inc.py out.inc name=file.frag|.comp ... (needs glslc, or
glslang: GLSLANG=<path> or glslang / glslangValidator on PATH; the stage follows the extension)."""
import shutil, struct, subprocess, sys, tempfile, os

GLSLC = shutil.which("glslc")
GLSLANG = os.environ.get("GLSLANG") or shutil.which("glslang") or shutil.which("glslangValidator")

out = sys.argv[1]
tool = "glslc -O" if GLSLC else "glslang -V"
lines = ["// Generated by tools/gen_spirv_inc.py from tools/shaders (%s --target-env=vulkan1.0). Do not edit.\n" % tool]
for spec in sys.argv[2:]:
    name, path = spec.split("=")
    with tempfile.TemporaryDirectory() as d:
        spv = os.path.join(d, "x.spv")
        stage = "comp" if path.endswith(".comp") else "frag"
        if GLSLC:
            subprocess.check_call([GLSLC, "-O", "--target-env=vulkan1.0", "-fshader-stage=" + stage, path, "-o", spv])
        else:
            subprocess.check_call([GLSLANG, "-V", "--target-env", "vulkan1.0", "-S", stage, path, "-o", spv],
                                  stdout=subprocess.DEVNULL)
        data = open(spv, "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    lines.append("// %s\nconst uint32_t %s[] = {\n" % (path, name))
    for i in range(0, len(words), 9):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 9]) + ",\n")
    lines.append("};\n")
open(out, "w").write("".join(lines))
